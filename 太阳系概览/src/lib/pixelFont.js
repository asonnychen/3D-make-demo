const GW = 5
const GH = 7

// 在 2D 上下文里按像素格绘制文本
export function drawPixelText(ctx, text, x, y, scale, color, letterGap = 1) {
  ctx.fillStyle = color
  const chars = String(text).toUpperCase().split('')
  let cursor = x
  for (const ch of chars) {
    const glyph = GLYPHS[ch] || GLYPHS[' ']
    for (let row = 0; row < GH; row += 1) {
      const line = glyph[row]
      for (let col = 0; col < GW; col += 1) {
        if (line[col] === '1') {
          ctx.fillRect(cursor + col * scale, y + row * scale, scale, scale)
        }
      }
    }
    cursor += (GW + letterGap) * scale
  }
  return cursor - x - letterGap * scale
}

export function measurePixelText(text, scale, letterGap = 1) {
  const n = String(text).length
  return Math.max(0, n * (GW + letterGap) * scale - letterGap * scale)
}

// 生成一张只含像素字的画布（用于页头与开场标题）
export function makePixelTitle(text, { scale = 4, color = '#e9ebee', gap = 1, padding = 0 } = {}) {
  const canvas = document.createElement('canvas')
  const width = measurePixelText(text, scale, gap) + padding * 2
  const height = GH * scale + padding * 2
  canvas.width = Math.max(1, Math.ceil(width))
  canvas.height = Math.max(1, Math.ceil(height))
  const ctx = canvas.getContext('2d')
  ctx.imageSmoothingEnabled = false
  drawPixelText(ctx, text, padding, padding, scale, color, gap)
  return canvas
}
